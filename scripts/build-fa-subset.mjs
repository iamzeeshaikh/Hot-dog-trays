/**
 * Build a Font Awesome subset containing only the icons this site actually uses.
 *
 * The full package costs 27KB of render-blocking CSS (86% of it rules for icons
 * we never render) plus 119KB + 115KB of webfont on the 28 pages that show an
 * icon. This emits:
 *
 *   public/fonts/fa-solid-subset.woff2
 *   public/fonts/fa-brands-subset.woff2
 *   src/styles/fontawesome-subset.css
 *
 * Run it after adding or removing an icon, then commit the three outputs:
 *
 *   node scripts/build-fa-subset.mjs
 *
 * It needs fontTools on PATH (`pip install fonttools brotli`, or point
 * PYFTSUBSET at a venv's pyftsubset). Because the outputs are committed, a
 * normal `npm run build` does not need it.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '..');
const FA = path.join(ROOT, 'node_modules', '@fortawesome', 'fontawesome-free');
const PYFTSUBSET = process.env.PYFTSUBSET || 'pyftsubset';

/** Every `fa-*` class name written anywhere in src/. */
function usedIconNames() {
  const names = new Set();
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.')) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.(astro|ts|tsx|js|mjs|json|md)$/.test(entry.name)) {
        for (const m of readFileSync(full, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) {
          names.add(m[1]);
        }
      }
    }
  };
  walk(path.join(ROOT, 'src'));
  return names;
}

/** name -> codepoint, parsed out of Font Awesome's own CSS. */
function codepointMap(cssFile) {
  const css = readFileSync(path.join(FA, 'css', cssFile), 'utf8');
  const map = new Map();
  // `.fa-truck-fast,.fa-shipping-fast{--fa:"\f48b"}` — one rule, many aliases.
  for (const m of css.matchAll(/((?:\.fa-[a-z0-9-]+,)*\.fa-[a-z0-9-]+)\{--fa:"([^"]+)"\}/g)) {
    // Values are either a hex escape (`\f48b`), an escaped literal (`\!`) or a
    // bare character (`A`) — the ASCII-glyph icons use the latter two.
    const raw = m[2];
    const hex = /^\\([0-9a-f]{2,6})\s*$/i.exec(raw);
    const cp = hex ? String.fromCodePoint(parseInt(hex[1], 16)) : raw.replace(/^\\/, '');
    for (const sel of m[1].split(',')) map.set(sel.replace('.fa-', ''), cp);
  }
  return map;
}

const used = usedIconNames();
// brands.min.css carries the codepoints for the brand marks; every other
// codepoint (the classic solid set) is defined once in fontawesome.min.css —
// solid.min.css holds only the @font-face and the .fas base rule.
const brands = codepointMap('brands.min.css');
const solid = codepointMap('fontawesome.min.css');

const families = [
  { key: 'solid', font: 'fa-solid-900.woff2', weight: 900, map: solid },
  { key: 'brands', font: 'fa-brands-400.woff2', weight: 400, map: brands },
];

mkdirSync(path.join(ROOT, 'public', 'fonts'), { recursive: true });

const rules = [];
const unmatched = new Set(used);

for (const family of families) {
  // Brands wins ties: fa-square exists in both, and a brand mark is always
  // written with `fab`, so keeping it in the solid subset too is dead weight.
  const picked = [...used]
    .filter((n) => family.map.has(n))
    .filter((n) => family.key === 'brands' || !brands.has(n))
    .sort();
  if (!picked.length) continue;

  const chars = [...new Set(picked.map((n) => family.map.get(n)))];
  const out = path.join(ROOT, 'public', 'fonts', `fa-${family.key}-subset.woff2`);
  execFileSync(PYFTSUBSET, [
    path.join(FA, 'webfonts', family.font),
    `--output-file=${out}`,
    `--unicodes=${chars.map((c) => 'U+' + c.codePointAt(0).toString(16)).join(',')}`,
    '--flavor=woff2',
    '--layout-features=',
    '--no-hinting',
    '--desubroutinize',
  ]);

  for (const n of picked) {
    unmatched.delete(n);
    const cp = family.map.get(n).codePointAt(0).toString(16);
    // A trailing space terminates the CSS hex escape, so an icon followed by a
    // real character in the same string can never be misread.
    rules.push(`.fa-${n} { --fa: "\\${cp} "; }`);
  }
  const before = statSync(path.join(FA, 'webfonts', family.font)).size;
  console.log(
    `${family.key}: ${picked.length} icons, ${(before / 1024) | 0}KB -> ${(statSync(out).size / 1024) | 0}KB`,
  );
}

if (unmatched.size) {
  // Not necessarily a problem: `fa-` also prefixes local class names such as
  // .faq-*. Listed so a genuine typo in an icon name is visible.
  console.log(`not Font Awesome icon names (ignored): ${[...unmatched].sort().join(', ')}`);
}

const css = `/* GENERATED by scripts/build-fa-subset.mjs — do not edit by hand.
 *
 * Font Awesome 7 Free, subset to the ${rules.length} icons this site renders.
 * Replaces the full fontawesome.css + solid.css + brands.css imports.
 */
@font-face {
  font-family: "Font Awesome 7 Free Solid";
  font-style: normal;
  font-weight: 900;
  font-display: block;
  src: url("/fonts/fa-solid-subset.woff2") format("woff2");
}
@font-face {
  font-family: "Font Awesome 7 Brands";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("/fonts/fa-brands-subset.woff2") format("woff2");
}

.fas,
.fab {
  display: var(--fa-display, inline-block);
  font-style: normal;
  font-variant: normal;
  font-weight: 900;
  line-height: 1;
  text-rendering: auto;
  -webkit-font-smoothing: antialiased;
}
.fas { font-family: "Font Awesome 7 Free Solid"; }
.fab { font-family: "Font Awesome 7 Brands"; font-weight: 400; }

.fas::before,
.fab::before {
  content: var(--fa);
}

${rules.sort().join('\n')}
`;
writeFileSync(path.join(ROOT, 'src', 'styles', 'fontawesome-subset.css'), css);
console.log(`wrote src/styles/fontawesome-subset.css (${(css.length / 1024).toFixed(1)}KB, ${rules.length} icons)`);
